CREATE TABLE command_usage_event (
    id BIGINT NOT NULL AUTO_INCREMENT,
    time_created DATETIME(3) NOT NULL,
    time_updated DATETIME(3) NOT NULL,
    event_uuid VARCHAR(64) NOT NULL,
    user_id BIGINT NOT NULL,
    command_name VARCHAR(128) NOT NULL,
    toolset_name VARCHAR(128) NULL,
    trigger_type VARCHAR(32) NOT NULL,
    evidence_type VARCHAR(32) NOT NULL,
    command_version VARCHAR(64) NULL,
    installation_id VARCHAR(64) NULL,
    client_session_id VARCHAR(256) NOT NULL,
    generation_id VARCHAR(256) NOT NULL,
    ai_generation_id BIGINT NULL,
    project_key VARCHAR(128) NULL,
    client VARCHAR(64) NOT NULL,
    client_version VARCHAR(64) NULL,
    invoked_at DATETIME(3) NOT NULL,
    received_at DATETIME(3) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_command_usage_event_uuid UNIQUE (event_uuid),
    CONSTRAINT fk_command_usage_user FOREIGN KEY (user_id) REFERENCES iam_user(id) ON DELETE RESTRICT,
    CONSTRAINT fk_command_usage_generation FOREIGN KEY (ai_generation_id) REFERENCES ai_generation_event(id) ON DELETE SET NULL,
    INDEX idx_command_usage_user_time (user_id, invoked_at),
    INDEX idx_command_usage_name_time (command_name, invoked_at),
    INDEX idx_command_usage_toolset_time (toolset_name, invoked_at),
    INDEX idx_command_usage_generation (ai_generation_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
