  attempt_no INT NOT NULL,
  candidate_id BIGINT NOT NULL,
  candidate_revision INT NOT NULL,
  submission_id BIGINT NULL,
  source_commit_sha CHAR(40) NOT NULL,
  manifest_hash CHAR(64) NOT NULL,
  rule_version VARCHAR(40) NOT NULL,
  package_status VARCHAR(32) NOT NULL DEFAULT 'PREPARING',
  source_index_artifact_version_id BIGINT NULL,
  stage_wiki_node_token VARCHAR(128) NULL,
  stage_wiki_obj_token VARCHAR(128) NULL,
  confirmed_by BIGINT NOT NULL,
  confirmed_at DATETIME(3) NOT NULL,
  completed_at DATETIME(3) NULL,
  last_error_code VARCHAR(80) NULL,
  version_no INT NOT NULL DEFAULT 0,
  time_created DATETIME(3) NOT NULL,
  time_updated DATETIME(3) NOT NULL,
  CONSTRAINT fk_asdm_package_requirement FOREIGN KEY(requirement_id) REFERENCES collab_project(id) ON DELETE RESTRICT,
  CONSTRAINT fk_asdm_package_stage FOREIGN KEY(stage_id) REFERENCES collab_stage(id) ON DELETE RESTRICT,
  CONSTRAINT fk_asdm_package_candidate FOREIGN KEY(candidate_id) REFERENCES collab_asdm_candidate(id) ON DELETE RESTRICT,
  CONSTRAINT fk_asdm_package_submission FOREIGN KEY(submission_id) REFERENCES collab_submission(id) ON DELETE RESTRICT,
  CONSTRAINT fk_asdm_package_index_version FOREIGN KEY(source_index_artifact_version_id) REFERENCES collab_artifact_version(id) ON DELETE RESTRICT,
  CONSTRAINT fk_asdm_package_confirmer FOREIGN KEY(confirmed_by) REFERENCES iam_user(id) ON DELETE RESTRICT,
  CONSTRAINT uk_asdm_package_stage_attempt UNIQUE(stage_id,attempt_no),
  CONSTRAINT uk_asdm_package_candidate_revision UNIQUE(candidate_id,candidate_revision),
  INDEX idx_asdm_package_status(package_status,time_updated)
