CREATE TABLE collab_requirement_progress_doc (
  id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  requirement_id BIGINT NOT NULL,
  wiki_space_id VARCHAR(128) NULL,
  wiki_parent_node_token VARCHAR(128) NULL,
  wiki_node_token VARCHAR(128) NULL,
  document_token VARCHAR(128) NULL,
  document_url VARCHAR(2048) NULL,
  status VARCHAR(32) NOT NULL DEFAULT 'PENDING_CREATE',
  desired_revision BIGINT NOT NULL DEFAULT 1,
  applied_revision BIGINT NOT NULL DEFAULT 0,
  last_snapshot_sha256 CHAR(64) NULL,
  block_map_json JSON NULL,
  last_applied_event_id BIGINT NULL,
  bootstrap_state VARCHAR(32) NOT NULL DEFAULT 'PENDING',
  bootstrap_version INT NOT NULL DEFAULT 0,
  bootstrap_started_at DATETIME(3) NULL,
  bootstrap_completed_at DATETIME(3) NULL,
  bootstrap_last_error_code VARCHAR(96) NULL,
  lease_owner VARCHAR(128) NULL,
  lease_until DATETIME(3) NULL,
  last_error_code VARCHAR(96) NULL,
  attempts INT NOT NULL DEFAULT 0,
  last_synced_at DATETIME(3) NULL,
  time_created DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  time_updated DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  CONSTRAINT uk_req_progress_doc UNIQUE (requirement_id),
  CONSTRAINT fk_req_progress_requirement FOREIGN KEY (requirement_id) REFERENCES collab_project(id) ON DELETE RESTRICT,
  INDEX idx_req_progress_work (status,lease_until,desired_revision)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE collab_requirement_progress_event (
  id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  requirement_id BIGINT NOT NULL,
  stage_id BIGINT NULL,
  attempt_no INT NULL,
  event_type VARCHAR(64) NOT NULL,
  event_key VARCHAR(255) NOT NULL,
  source_type VARCHAR(48) NOT NULL,
  source_id VARCHAR(96) NOT NULL,
  actor_user_id BIGINT NULL,
  occurred_at DATETIME(3) NOT NULL,
  summary VARCHAR(1200) NOT NULL,
  target_url VARCHAR(2048) NULL,
  detail_json JSON NULL,
  remote_row_marker VARCHAR(128) NULL,
  remote_write_state VARCHAR(32) NOT NULL DEFAULT 'PENDING',
  time_created DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  CONSTRAINT uk_req_progress_event UNIQUE (requirement_id,event_key),
  CONSTRAINT fk_req_progress_event_requirement FOREIGN KEY (requirement_id) REFERENCES collab_project(id) ON DELETE RESTRICT,
  INDEX idx_req_progress_events (requirement_id,occurred_at,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
