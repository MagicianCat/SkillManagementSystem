CREATE TABLE dim_development_stage (
    category_id BIGINT NOT NULL,
    category_key VARCHAR(64) NOT NULL,
    category_name VARCHAR(128) NOT NULL,
    parent_category_id BIGINT NULL,
    stage_key VARCHAR(64) NOT NULL,
    stage_name VARCHAR(128) NOT NULL,
    stage_enum VARCHAR(32) NOT NULL,
    category_level TINYINT NOT NULL,
    sort_order INT NOT NULL,
    status VARCHAR(32) NOT NULL,
    PRIMARY KEY (category_id),
    CONSTRAINT uk_etl_stage_category_key UNIQUE (category_key),
    INDEX idx_etl_stage_parent (parent_category_id, sort_order),
    INDEX idx_etl_stage_key (stage_key, category_level)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

