CREATE TABLE wiki_feishu_transfer_job (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    actor_user_id BIGINT NOT NULL,
    direction VARCHAR(16) NOT NULL,
    operation VARCHAR(16) NULL,
    format VARCHAR(32) NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'PENDING',
    idempotency_key VARCHAR(80) NOT NULL,
    request_hash CHAR(64) NOT NULL,
    wiki_document_id BIGINT NULL,
    wiki_revision_id BIGINT NULL,
    expected_wiki_version_no INT NULL,
    source_type VARCHAR(16) NULL,
    source_token VARCHAR(512) NULL,
    source_audience VARCHAR(24) NULL,
    content_mode VARCHAR(16) NULL,
    target_title VARCHAR(255) NULL,
    target_team_id BIGINT NULL,
    target_parent_wiki_id BIGINT NULL,
    target_knowledge_category VARCHAR(32) NULL,
    target_skill_ids_json JSON NULL,
    folder_token VARCHAR(512) NULL,
    feishu_output_token VARCHAR(512) NULL,
    feishu_output_url VARCHAR(1500) NULL,
    conversion_warnings_json JSON NULL,
    attempt_count INT NOT NULL DEFAULT 0,
    claimed_at DATETIME(3) NULL,
    error_code VARCHAR(80) NULL,
    error_message VARCHAR(1024) NULL,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    completed_at DATETIME(3) NULL,
    UNIQUE KEY uk_wiki_feishu_actor_idempotency (actor_user_id,idempotency_key),
    KEY ix_wiki_feishu_status (status,created_at),
    KEY ix_wiki_feishu_wiki (wiki_document_id,created_at),
    CONSTRAINT fk_wiki_feishu_job_actor FOREIGN KEY (actor_user_id) REFERENCES iam_user(id)
);

CREATE TABLE wiki_feishu_document_link (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    wiki_document_id BIGINT NOT NULL,
    source_direction VARCHAR(16) NOT NULL,
    feishu_document_token VARCHAR(512) NOT NULL,
    feishu_document_type VARCHAR(32) NOT NULL,
    feishu_document_url VARCHAR(1500) NULL,
    wiki_revision_id BIGINT NULL,
    transfer_job_id BIGINT NOT NULL,
    actor_user_id BIGINT NOT NULL,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    KEY ix_wiki_feishu_link_wiki (wiki_document_id),
    KEY ix_wiki_feishu_link_doc (feishu_document_token),
    CONSTRAINT fk_wiki_feishu_link_wiki FOREIGN KEY (wiki_document_id) REFERENCES wiki_document(id),
    CONSTRAINT fk_wiki_feishu_link_job FOREIGN KEY (transfer_job_id) REFERENCES wiki_feishu_transfer_job(id)
);
