CREATE TABLE collab_asdm_sync_job (
  id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  requirement_id BIGINT NOT NULL,
  requested_by BIGINT NOT NULL,
  idempotency_key VARCHAR(128) NOT NULL,
  group_revision INT NOT NULL,
  default_version VARCHAR(64) NOT NULL,
  rule_hash CHAR(64) NOT NULL,
  head_sha CHAR(40) NULL,
  status VARCHAR(32) NOT NULL DEFAULT 'QUEUED',
  last_error_code VARCHAR(100) NULL,
  time_created DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  time_updated DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  CONSTRAINT fk_asdm_sync_job_requirement FOREIGN KEY(requirement_id) REFERENCES collab_project(id),
  CONSTRAINT fk_asdm_sync_job_actor FOREIGN KEY(requested_by) REFERENCES iam_user(id),
  CONSTRAINT uk_asdm_sync_job_idempotency UNIQUE(requirement_id,idempotency_key),
  INDEX idx_asdm_sync_job_status(status,time_updated)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE collab_asdm_sync_stage (
  id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  job_id BIGINT NOT NULL,
  stage_id BIGINT NOT NULL,
  stage_key VARCHAR(48) NOT NULL,
  stage_status_snapshot VARCHAR(32) NOT NULL,
  action VARCHAR(32) NOT NULL,
  status VARCHAR(32) NOT NULL DEFAULT 'PENDING',
  found_count INT NOT NULL DEFAULT 0,
  new_count INT NOT NULL DEFAULT 0,
  updated_count INT NOT NULL DEFAULT 0,
  uncertain_count INT NOT NULL DEFAULT 0,
  supplemental_node_token VARCHAR(255) NULL,
  supplemental_index_token VARCHAR(255) NULL,
  supplemental_index_url VARCHAR(2048) NULL,
  last_error_code VARCHAR(100) NULL,
  time_created DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  time_updated DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  CONSTRAINT fk_asdm_sync_stage_job FOREIGN KEY(job_id) REFERENCES collab_asdm_sync_job(id),
  CONSTRAINT fk_asdm_sync_stage_stage FOREIGN KEY(stage_id) REFERENCES collab_stage(id),
  CONSTRAINT uk_asdm_sync_stage UNIQUE(job_id,stage_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE collab_asdm_sync_file (
  id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  sync_stage_id BIGINT NOT NULL,
  source_path_sha256 CHAR(64) NOT NULL,
  source_path VARCHAR(1600) NOT NULL,
  blob_sha CHAR(40) NOT NULL,
  content_sha256 CHAR(64) NOT NULL,
  size_bytes BIGINT NOT NULL,
  media_type VARCHAR(128) NOT NULL,
  classification VARCHAR(24) NOT NULL,
  delivery_mode VARCHAR(24) NOT NULL,
  sync_action VARCHAR(24) NOT NULL,
  publish_status VARCHAR(32) NOT NULL DEFAULT 'PENDING',
  snapshot_storage_key VARCHAR(1024) NULL,
  source_git_url VARCHAR(2048) NULL,
  feishu_target_id VARCHAR(255) NULL,
  feishu_node_token VARCHAR(255) NULL,
  feishu_url VARCHAR(2048) NULL,
  last_error_code VARCHAR(100) NULL,
  attempts INT NOT NULL DEFAULT 0,
  time_created DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  time_updated DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  CONSTRAINT fk_asdm_sync_file_stage FOREIGN KEY(sync_stage_id) REFERENCES collab_asdm_sync_stage(id),
  CONSTRAINT uk_asdm_sync_file_path UNIQUE(sync_stage_id,source_path_sha256),
  INDEX idx_asdm_sync_file_ready(sync_stage_id,publish_status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE collab_asdm_published_file_registry (
  id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  requirement_id BIGINT NOT NULL,
  stage_id BIGINT NOT NULL,
  source_path_sha256 CHAR(64) NOT NULL,
  source_path VARCHAR(1600) NOT NULL,
  latest_content_sha256 CHAR(64) NOT NULL,
  version_no INT NOT NULL DEFAULT 1,
  last_feishu_url VARCHAR(2048) NULL,
  last_sync_file_id BIGINT NULL,
  time_updated DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  CONSTRAINT fk_asdm_registry_requirement FOREIGN KEY(requirement_id) REFERENCES collab_project(id),
  CONSTRAINT fk_asdm_registry_stage FOREIGN KEY(stage_id) REFERENCES collab_stage(id),
  CONSTRAINT fk_asdm_registry_sync_file FOREIGN KEY(last_sync_file_id) REFERENCES collab_asdm_sync_file(id),
  CONSTRAINT uk_asdm_registry_path UNIQUE(requirement_id,stage_id,source_path_sha256)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
