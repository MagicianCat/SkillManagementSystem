CREATE TABLE dwd_command_usage_detail (
    command_event_id VARCHAR(64) NOT NULL,
    generation_id VARCHAR(256) NULL,
    user_oa VARCHAR(128) NULL,
    project_key VARCHAR(128) NULL,
    req_id VARCHAR(256) NULL,
    req_id_source VARCHAR(32) NULL,
    command_name VARCHAR(128) NOT NULL,
    toolset_name VARCHAR(128) NULL,
    command_version VARCHAR(64) NULL,
    trigger_type VARCHAR(32) NOT NULL,
    evidence_type VARCHAR(32) NOT NULL,
    client VARCHAR(64) NOT NULL,
    client_version VARCHAR(64) NULL,
    invoked_at DATETIME(3) NOT NULL,
    received_at DATETIME(3) NOT NULL,
    etl_updated_at DATETIME(3) NOT NULL,
    PRIMARY KEY (command_event_id),
    INDEX idx_etl_command_generation (generation_id),
    INDEX idx_etl_command_req_time (req_id, invoked_at),
    INDEX idx_etl_command_user_time (user_oa, invoked_at),
    INDEX idx_etl_command_toolset_time (toolset_name, command_name, invoked_at),
    INDEX idx_etl_command_project_time (project_key, invoked_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
